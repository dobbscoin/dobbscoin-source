// Deterministic inputs, so a failure reproduces.
struct SplitMix64 {
    uint64_t s;
    explicit SplitMix64(uint64_t seed) : s(seed) {}
    uint64_t Next()
    {
        uint64_t z = (s += 0x9e3779b97f4a7c15ULL);
        z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ULL;
        z = (z ^ (z >> 27)) * 0x94d049bb133111ebULL;
        return z ^ (z >> 31);
    }
};

std::vector<ScryptImpl> ImplsUnderTest()
{
    std::vector<ScryptImpl> impls;
    const char* pszForced = getenv("DOBBSCOIN_MINERSCRYPT");
    if (pszForced && *pszForced) {
        ScryptImpl impl;
        BOOST_REQUIRE_MESSAGE(ScryptImplFromName(pszForced, impl), "unknown DOBBSCOIN_MINERSCRYPT=" << pszForced);
        BOOST_REQUIRE_MESSAGE(ScryptImplSupported(impl), "DOBBSCOIN_MINERSCRYPT=" << pszForced << " is not supported on this CPU");
        impls.push_back(impl);
        return impls;
    }
    for (int i = 0; i < SCRYPT_IMPL_COUNT; i++)
        if (ScryptImplSupported((ScryptImpl)i))
            impls.push_back((ScryptImpl)i);
    return impls;
}

std::string ImplList(const std::vector<ScryptImpl>& impls)
{
    std::string s;
    for (ScryptImpl impl : impls)
        s += std::string(s.empty() ? "" : ", ") + ScryptImplDescription(impl);
    return s;
}

uint256 GenericScrypt(const unsigned char* input80)
{
    uint256 hash;
    scrypt_1024_1_1_256((const char*)input80, (char*)hash.begin());
    return hash;
}

// Hash inputs[i] with impl, ScryptImplLanes(impl) at a time (the last batch
// wraps around to the first inputs), and count the lanes that differ from
// expected[i].
int CountMismatches(ScryptImpl impl, const std::vector<unsigned char>& inputs, const std::vector<uint256>& expected)
{
    const int nLanes = ScryptImplLanes(impl);
    const int nInputs = (int)expected.size();
    std::vector<unsigned char> scratch(ScryptNwayScratchpadSize(impl));
    unsigned char in[SCRYPT_NWAY_MAX_LANES * 80];
    unsigned char out[SCRYPT_NWAY_MAX_LANES * 32];
    int nMismatches = 0;
    for (int i = 0; i < nInputs; i += nLanes) {
        for (int l = 0; l < nLanes; l++)
            memcpy(in + 80 * l, &inputs[80 * ((i + l) % nInputs)], 80);
        scrypt_1024_1_1_256_nway(impl, in, out, &scratch[0]);
        for (int l = 0; l < nLanes && i + l < nInputs; l++) {
            if (memcmp(out + 32 * l, expected[i + l].begin(), 32) != 0) {
                if (nMismatches < 5) {
                    uint256 got;
                    memcpy(got.begin(), out + 32 * l, 32);
                    BOOST_ERROR(ScryptImplDescription(impl) << " input " << (i + l) << " lane " << l << ": got " << got.GetHex() << ", generic " << expected[i + l].GetHex());
                }
                nMismatches++;
            }
        }
    }
    return nMismatches;
}

