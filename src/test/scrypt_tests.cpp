BOOST_AUTO_TEST_CASE(scrypt_nway_selection)
{
    for (int i = 0; i < SCRYPT_IMPL_COUNT; i++) {
        ScryptImpl impl = (ScryptImpl)i, parsed;
        BOOST_CHECK(ScryptImplFromName(ScryptImplName(impl), parsed));
        BOOST_CHECK(parsed == impl);
        BOOST_CHECK(ScryptImplLanes(impl) >= 1 && ScryptImplLanes(impl) <= SCRYPT_NWAY_MAX_LANES);
        BOOST_CHECK(ScryptNwayScratchpadSize(impl) >= (size_t)SCRYPT_SCRATCHPAD_SIZE);
    }
    ScryptImpl dummy;
    BOOST_CHECK(!ScryptImplFromName("auto", dummy));
    BOOST_CHECK(!ScryptImplFromName("AVX2", dummy));
    BOOST_CHECK(!ScryptImplFromName("", dummy));
    BOOST_CHECK(ScryptImplSupported(ScryptImpl::GENERIC));
    BOOST_CHECK(ScryptImplSupported(ScryptImplBest()));
    BOOST_CHECK_EQUAL(ScryptImplDescription(ScryptImpl::AVX2), "AVX2 (6-way)");
#if defined(__x86_64__) && !defined(__ILP32__)
    BOOST_CHECK(ScryptImplSupported(ScryptImpl::SSE2));
    BOOST_CHECK(ScryptImplBest() != ScryptImpl::GENERIC);
#else
    BOOST_CHECK(ScryptImplBest() == ScryptImpl::GENERIC);
#endif
    printf("scrypt_tests: CPU: %s; best: %s; testing: %s\n", ScryptCpuFeatures().c_str(),
           ScryptImplDescription(ScryptImplBest()).c_str(), ImplList(ImplsUnderTest()).c_str());
}

BOOST_AUTO_TEST_CASE(scrypt_nway_mainnet_headers)
{
    const int nHeaders = sizeof(MAINNET_HEADERS) / sizeof(MAINNET_HEADERS[0]);
    std::vector<unsigned char> inputs;
    std::vector<uint256> expected;
    for (int i = 0; i < nHeaders; i++) {
        std::vector<unsigned char> header = ParseHex(MAINNET_HEADERS[i].pszHeader);
        BOOST_REQUIRE_EQUAL(header.size(), 80U);
        // The data is what it claims to be: SHA256d is the block hash ...
        BOOST_CHECK_EQUAL(Hash(header.begin(), header.end()).GetHex(), MAINNET_HEADERS[i].pszHash);
        // ... and the generic scrypt meets the header's own nBits, as a
        // mainnet block's proof of work must.
        uint256 pow = GenericScrypt(&header[0]);
        uint32_t nBits = header[72] | header[73] << 8 | header[74] << 16 | (uint32_t)header[75] << 24;
        uint256 target;
        target.SetCompact(nBits);
        BOOST_CHECK_MESSAGE(pow <= target, "height " << MAINNET_HEADERS[i].nHeight << ": scrypt " << pow.GetHex() << " > target " << target.GetHex());
        inputs.insert(inputs.end(), header.begin(), header.end());
        expected.push_back(pow);
    }
    for (ScryptImpl impl : ImplsUnderTest()) {
        int nBad = CountMismatches(impl, inputs, expected);
        BOOST_CHECK_EQUAL(nBad, 0);
        printf("scrypt_tests: %-14s %4d mainnet headers, %d mismatches vs generic\n", ScryptImplDescription(impl).c_str(), nHeaders, nBad);
    }
}

BOOST_AUTO_TEST_CASE(scrypt_nway_random_inputs)
{
    int nInputs = 3072;
    if (const char* psz = getenv("SCRYPT_TEST_INPUTS"))
        nInputs = std::max(1, atoi(psz));

    SplitMix64 rng(0x424f42u); // "BOB"
    std::vector<unsigned char> inputs(80 * nInputs);
    for (size_t i = 0; i < inputs.size(); i += 8) {
        uint64_t r = rng.Next();
        memcpy(&inputs[i], &r, 8);
    }
    // The second half looks like mining: one header, consecutive nonces.
    for (int i = nInputs / 2; i < nInputs; i++) {
        memcpy(&inputs[80 * i], &inputs[80 * (nInputs / 2)], 76);
        uint32_t nNonce = 0xfffffff0u + (uint32_t)i; // wraps through 0
        memcpy(&inputs[80 * i + 76], &nNonce, 4);
    }
    std::vector<uint256> expected;
    for (int i = 0; i < nInputs; i++)
        expected.push_back(GenericScrypt(&inputs[80 * i]));

    for (ScryptImpl impl : ImplsUnderTest()) {
        int nBad = CountMismatches(impl, inputs, expected);
        BOOST_CHECK_EQUAL(nBad, 0);
        printf("scrypt_tests: %-14s %4d random inputs, %d mismatches vs generic\n", ScryptImplDescription(impl).c_str(), nInputs, nBad);
    }

    // Every lane identical, and a lane differing from its neighbours by one
    // bit: the lanes must not leak into each other.
    for (ScryptImpl impl : ImplsUnderTest()) {
        const int nLanes = ScryptImplLanes(impl);
        std::vector<unsigned char> scratch(ScryptNwayScratchpadSize(impl));
        unsigned char in[SCRYPT_NWAY_MAX_LANES * 80], out[SCRYPT_NWAY_MAX_LANES * 32];
        for (int flip = -1; flip < nLanes; flip++) {
            for (int l = 0; l < nLanes; l++) {
                memcpy(in + 80 * l, &inputs[0], 80);
                if (l == flip)
                    in[80 * l + 40] ^= 0x01;
            }
            scrypt_1024_1_1_256_nway(impl, in, out, &scratch[0]);
            for (int l = 0; l < nLanes; l++)
                BOOST_CHECK(memcmp(out + 32 * l, GenericScrypt(in + 80 * l).begin(), 32) == 0);
        }
    }
}

namespace {
void BenchWorker(ScryptImpl impl, int64_t nStopMillis, std::atomic<int64_t>* pnHashes)
{
    const int nLanes = ScryptImplLanes(impl);
    std::vector<unsigned char> scratch(ScryptNwayScratchpadSize(impl));
    unsigned char in[SCRYPT_NWAY_MAX_LANES * 80] = {}, out[SCRYPT_NWAY_MAX_LANES * 32];
    uint32_t nNonce = 0;
    int64_t nDone = 0;
    while (GetTimeMillis() < nStopMillis) {
        for (int l = 0; l < nLanes; l++, nNonce++)
            memcpy(in + 80 * l + 76, &nNonce, 4);
        scrypt_1024_1_1_256_nway(impl, in, out, &scratch[0]);
        nDone += nLanes;
    }
    *pnHashes += nDone;
}

double BenchRun(ScryptImpl impl, int nThreads, double dSeconds)
{
    std::atomic<int64_t> nHashes(0);
    int64_t nStart = GetTimeMillis();
    int64_t nStop = nStart + (int64_t)(dSeconds * 1000);
    boost::thread_group threads;
    for (int t = 0; t < nThreads; t++)
        threads.create_thread(boost::bind(&BenchWorker, impl, nStop, &nHashes));
    threads.join_all();
    return 1000.0 * nHashes / (GetTimeMillis() - nStart);
}
} // namespace

